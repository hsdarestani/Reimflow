/* Reimflow Flow Challenge: deterministic scoring and integration smoke checks */
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {runInNewContext} from "node:vm";
const path=(name)=>new URL("../"+name,import.meta.url);
const scoring=readFileSync(path("flow-scoring.js"),"utf8");
const timingContext={};
runInNewContext(scoring,timingContext,{filename:"flow-scoring.js"});
const T=timingContext.ReimflowTiming;
assert.ok(T);
assert.equal(T.BEATS,16);
assert.equal(T.COUNT_IN,4);
assert.equal(T.WINDOW_MS,190);
assert.deepEqual({...T.judgeOffset(0)},{kind:"perfect",points:100,label:"PERFEKT!"});
assert.equal(T.judgeOffset(-50).kind,"perfect");
assert.equal(T.judgeOffset(56).kind,"good");
assert.equal(T.judgeOffset(-115).kind,"good");
assert.equal(T.judgeOffset(116).kind,"okay");
assert.equal(T.judgeOffset(190).kind,"okay");
assert.equal(T.judgeOffset(191).kind,"miss");
assert.equal(T.judgeOffset(Infinity).kind,"miss");
assert.equal(T.judgeOffset(NaN).kind,"miss");
const p=T.judgeOffset(0),g=T.judgeOffset(85),miss=T.judgeOffset(250);
let result=T.scoreRound(Array.from({length:16},()=>p));
assert.equal(result.score,100);
assert.equal(result.perfect,16);
assert.equal(result.maxCombo,16);
assert.equal(result.title,"TAKTMEISTER");
result=T.scoreRound([p,p,g,miss,p]);
assert.equal(result.miss,12);
assert.equal(result.maxCombo,3);
assert.equal(result.perfect,3);
assert.equal(result.good,1);
assert.ok(result.score<30);
result=T.scoreRound([]);
assert.equal(result.score,0);
assert.equal(result.maxCombo,0);
for(const score of [0,59,60,77,78,92,93,100])assert.ok(T.rating(score).title.length>0);

const html=readFileSync(path("index.html"),"utf8");
const game=readFileSync(path("flow-challenge.js"),"utf8");
const css=readFileSync(path("flow-challenge.css"),"utf8");
const app=readFileSync(path("app.js"),"utf8");
assert.ok(html.includes('data-page="flow"'),"missing game page");
assert.equal((html.match(/data-go="flow"/g)||[]).length,3,"desktop, mobile and homepage CTA required");
assert.equal((html.match(/class="flow-beat" data-index=/g)||[]).length,16);
for(const [id,part] of [["flowStart","start"],["flowTap","inputHit"],["flowShare","share"],["flowStop","stop"],["flowBpm","selectedBpm"]]){
 assert.ok(html.includes('id="'+id+'"'),"missing UI "+id);
 assert.ok(game.includes(part),"missing game action "+part);
}
assert.ok(html.indexOf('flow-scoring.js?v=20261014-de1')<html.indexOf('flow-challenge.js?v=20261014-de1'));
assert.ok(app.includes('ReimflowFlowChallenge?.onPageChange(page)'));
assert.ok(html.includes('>IM TAKT TIPPEN</strong>'),"German rhythm pad label must load");
assert.ok(html.includes('>DEINE TAKTGENAUIGKEIT <span>'),"German results panel must load");
assert.ok(game.includes('"RUNDE BEENDET"'),"German completion state is required");
assert.ok(game.includes('" BESTE SERIE"'),"German combo counter is required");
assert.ok(!game.includes('label:"MISS"'),"No untranslated live missed beat notification");
assert.ok(!html.includes("TAP THE BEAT"),"No untranslated static rhythm prompt");
assert.ok(game.includes('navigator.mediaDevices.getUserMedia'));
assert.ok(game.includes('getByteTimeDomainData'));
assert.ok(game.includes('getTracks().forEach(t=>t.stop())'));
assert.ok(!game.includes("MediaRecorder"),"mic never records audio");
assert.ok(!game.includes('fetch('),"game must work without network requests");
const mobileUx=readFileSync(path("ux-simple.css"),"utf8");
assert.ok(mobileUx.includes("grid-template-columns: repeat(4, minmax(0, 1fr))"),"four-tab mobile dock needs four grid columns");
assert.ok(!css.includes("grid-template-columns:repeat(6,minmax(0,1fr))"),"Flow CSS must not override shared navigation");
assert.ok(css.includes('touch-action:manipulation'));
assert.equal((css.match(/{/g)||[]).length,(css.match(/}/g)||[]).length,"CSS braces balance");
console.log("Flow Challenge passed: scoring, 16-beat timing, 3 navigation entry points, mic isolation, mobile layout.");
